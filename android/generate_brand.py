#!/usr/bin/env python3
"""Write android/.../ui/BrandColors.kt from the iPhone's palette in
ios/AncientTrees/AncientTrees/Kit/Style.swift (`public static let x = Color(light:
0x.., dark: 0x..)`), so the two apps cannot drift. Run again when Style.swift
changes:  python3 android/generate_brand.py
"""
import pathlib
import re

ROOT = pathlib.Path(__file__).resolve().parent.parent
SWIFT = ROOT / "ios/AncientTrees/AncientTrees/Kit/Style.swift"
OUT = ROOT / "android/app/src/main/java/app/ancienttrees/ui/BrandColors.kt"

rows = re.findall(r"public static let (\w+) = Color\(light: 0x([0-9A-Fa-f]{6}), dark: 0x([0-9A-Fa-f]{6})\)",
                  SWIFT.read_text())
lines = [
    "// GENERATED by android/generate_brand.py from ios/.../Kit/Style.swift. Do not hand-edit:",
    "// the reasons for every colour are written beside it in the Swift.",
    "",
    "package app.ancienttrees.ui",
    "",
    "import androidx.compose.runtime.Immutable",
    "import androidx.compose.ui.graphics.Color",
    "",
    "@Immutable",
    "data class BrandColors(",
]
lines += [f"    val {n}: Color," for n, _, _ in rows]
lines += [")", "", "val LightBrand = BrandColors("]
lines += [f"    {n} = Color(0xFF{l.upper()})," for n, l, _ in rows]
lines += [")", "", "val DarkBrand = BrandColors("]
lines += [f"    {n} = Color(0xFF{d.upper()})," for n, _, d in rows]
lines += [")", ""]
OUT.write_text("\n".join(lines))
print(f"{len(rows)} colours -> {OUT.relative_to(ROOT)}")
