#!/usr/bin/env python3
"""Write the round flags the iPhone draws: flag-icons' square SVGs, as PNGs.

The iPhone fills a circle with the flat flag from the website's own set
(flag-icons 7.2.3, MIT, ios/AncientTrees/FLAGS-LICENSE.txt; CountryFlag in
AmbassadorBadge.swift), because the system's flag emoji waves at an angle and
cropped to a circle its stripes never run level (Hidde, 2026-10-19). Android
drew the emoji, so the Dutch flag lost its blue band (visual review 2026-11-11).

Each SVG in the iPhone's asset catalogue is rendered once on the Mac (Quick
Look, 120 px: a 28 dp circle at the densest screen) into res/drawable-nodpi,
and ui/Flags.kt maps the code to it. Run again when the catalogue changes:

    python3 android/generate_flags.py
"""
import pathlib
import shutil
import subprocess
import tempfile

ROOT = pathlib.Path(__file__).resolve().parent.parent
SRC = ROOT / "ios/AncientTrees/AncientTrees/Assets.xcassets/Flags"
RES = ROOT / "android/app/src/main/res/drawable-nodpi"
KT = ROOT / "android/app/src/main/java/app/ancienttrees/ui/Flags.kt"
LICENCE = ROOT / "android/FLAGS-LICENSE.txt"


def main():
    RES.mkdir(parents=True, exist_ok=True)
    codes = []
    with tempfile.TemporaryDirectory() as tmp:
        for d in sorted(SRC.glob("*.imageset")):
            svg = next(d.glob("*.svg"), None)
            if not svg:
                continue
            code = d.name.split(".")[0].lower()
            subprocess.run(["qlmanage", "-t", "-s", "120", "-o", tmp, str(svg)],
                           check=True, capture_output=True)
            png = pathlib.Path(tmp) / f"{svg.name}.png"
            shutil.move(str(png), RES / f"flag_{code}.png")
            codes.append(code)
    shutil.copy(ROOT / "ios/AncientTrees/FLAGS-LICENSE.txt", LICENCE)
    lines = [
        "// GENERATED by android/generate_flags.py from the iPhone's Flags catalogue",
        "// (flag-icons 7.2.3, MIT, android/FLAGS-LICENSE.txt). Do not edit by hand.",
        "",
        "package app.ancienttrees.ui",
        "",
        "import app.ancienttrees.R",
        "",
        "/** The flat round flag per lower-case ISO code, as CountryFlag draws it. */",
        "val FLAGS: Map<String, Int> = mapOf(",
    ]
    lines += [f'    "{c}" to R.drawable.flag_{c},' for c in codes]
    lines += [")", ""]
    KT.write_text("\n".join(lines))
    print(f"wrote {len(codes)} flags")


if __name__ == "__main__":
    main()
