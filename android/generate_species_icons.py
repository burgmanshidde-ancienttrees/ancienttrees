#!/usr/bin/env python3
"""Write android/.../map/SpeciesIcons.kt from site/src/lib/species-icons.ts.

The website's species silhouettes are the one source; the iPhone carries a
generated copy and so does Android. Run again when the website's set changes:

    python3 android/generate_species_icons.py

SVG path data is written out with every number and arc flag spelled apart,
because SVG lets an arc's two flags and the next number run together ("a6 5 0
106 5") and Android's path parser does not always read that the same way.
"""
import pathlib
import re

ROOT = pathlib.Path(__file__).resolve().parent.parent
SRC = ROOT / "site/src/lib/species-icons.ts"
OUT = ROOT / "android/app/src/main/java/app/ancienttrees/map/SpeciesIcons.kt"

ARGS = {"m": 2, "l": 2, "h": 1, "v": 1, "c": 6, "s": 4, "q": 4, "t": 2, "a": 7, "z": 0}
NUMBER = re.compile(r"[+-]?(?:\d+\.?\d*|\.\d+)(?:[eE][+-]?\d+)?")


def normalise(d):
    out, i, cmd, n = [], 0, None, 0
    while i < len(d):
        ch = d[i]
        if ch.isalpha():
            cmd, n = ch, 0
            out.append(ch)
            i += 1
            continue
        if ch in " ,\t\n":
            i += 1
            continue
        if cmd and cmd.lower() == "a" and n % 7 in (3, 4):
            out.append(ch)  # an arc flag is one character, always
            i += 1
            n += 1
            continue
        m = NUMBER.match(d, i)
        if not m:
            raise ValueError(f"cannot read {d[i:i+12]!r}")
        out.append(m.group(0))
        i = m.end()
        n += 1
    return " ".join(out)


def attrs(tag):
    return dict(re.findall(r'([a-z]+)="([^"]*)"', tag))


def parts(svg):
    rows = []
    for tag in re.findall(r"<(?:path|ellipse)[^>]*/>", svg):
        a = attrs(tag)
        alpha = float(a.get("opacity", "1"))
        if tag.startswith("<ellipse"):
            cx, cy, rx, ry = (float(a[k]) for k in ("cx", "cy", "rx", "ry"))
            rows.append(f'        Part.Oval({cx - rx}f, {cy - ry}f, {cx + rx}f, {cy + ry}f, {alpha}f)')
            continue
        rot = tr = "null"
        t = a.get("transform", "")
        if m := re.match(r"rotate\(([-\d.]+)[ ,]+([-\d.]+)[ ,]+([-\d.]+)\)", t):
            rot = f"floatArrayOf({m[1]}f, {m[2]}f, {m[3]}f)"
        elif m := re.match(r"translate\(([-\d.]+)[ ,]+([-\d.]+)\)", t):
            tr = f"floatArrayOf({m[1]}f, {m[2]}f)"
        elif t:
            raise ValueError(f"unknown transform {t}")
        rows.append(f'        Part.Shape("{normalise(a["d"])}", {alpha}f, {rot}, {tr})')
    return rows


def main():
    ts = SRC.read_text()
    block = ts.split("SPECIES_ICONS: Record<string, string> = {", 1)[1].split("\n};", 1)[0]
    icons = {}
    for key, body in re.findall(r"\n  (\w+):\s*\n((?:\s*'[^']*'\s*\+?)+),", block + ","):
        icons[key] = "".join(re.findall(r"'([^']*)'", body))
    arch = re.findall(r'\["(\w+)", \[([^\]]*)\]\]', ts)

    lines = [
        "// GENERATED by android/generate_species_icons.py from site/src/lib/species-icons.ts.",
        "// Do not hand-edit. The website, the iPhone and Android draw the same tree.",
        "",
        "package app.ancienttrees.map",
        "",
        "object SpeciesIcons {",
        "    sealed class Part {",
        "        abstract val alpha: Float",
        "        /** SVG path data in a 40 by 40 box, with rotate(angle, cx, cy) or translate(x, y). */",
        "        data class Shape(val d: String, override val alpha: Float, val rotate: FloatArray?, val translate: FloatArray?) : Part()",
        "        data class Oval(val left: Float, val top: Float, val right: Float, val bottom: Float, override val alpha: Float) : Part()",
        "    }",
        "",
        "    val icons: Map<String, List<Part>> = mapOf(",
    ]
    for key, svg in icons.items():
        lines.append(f'        "{key}" to listOf(')
        lines += [r + "," for r in parts(svg)]
        lines.append("        ),")
    lines += [
        "    )",
        "",
        "    /** Ordered: the first archetype whose needle appears in the common name wins. */",
        "    val archetypes: List<Pair<String, List<String>>> = listOf(",
    ]
    for key, needles in arch:
        lines.append(f'        "{key}" to listOf({needles.strip()}),')
    lines += [
        "    )",
        "",
        "    fun archetype(common: String): String {",
        "        val name = common.lowercase()",
        "        for ((key, needles) in archetypes) {",
        "            if (needles.any { name.contains(it) } && key in icons) return key",
        "        }",
        '        return "broadleaf"',
        "    }",
        "}",
        "",
    ]
    OUT.write_text("\n".join(lines))
    print(f"{len(icons)} shapes, {len(arch)} archetypes -> {OUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
